enum InterfaceLanguage: String, CaseIterable, Codable, Identifiable, Hashable {
    case english = "en"
    case simplifiedChinese = "zh-Hans"
    case japanese = "ja"
    case korean = "ko"
    case spanish = "es"
    case french = "fr"
    case german = "de"
    case vietnamese = "vi"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .english: "English"
        case .simplifiedChinese: "简体中文"
        case .japanese: "日本語"
        case .korean: "한국어"
        case .spanish: "Español"
        case .french: "Français"
        case .german: "Deutsch"
        case .vietnamese: "Tiếng Việt"
        }
    }

    var localeIdentifier: String { rawValue }

    func localized(_ key: InterfaceText, arguments: [CVarArg] = []) -> String {
        let format = Self.translations[self]?[key] ?? Self.translations[.english]?[key] ?? key.rawValue
        guard !arguments.isEmpty else { return format }
        return String(format: format, locale: Locale(identifier: localeIdentifier), arguments: arguments)
    }

