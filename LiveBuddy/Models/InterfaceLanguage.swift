@MainActor
extension AppState {
    func t(_ key: InterfaceText, _ arguments: CVarArg...) -> String {
        settings.interfaceLanguage.localized(key, arguments: arguments)
    }
}

extension AudioSource {
    func localizedTitle(language: InterfaceLanguage) -> String {
        switch self {
        case .screen:
            language.localized(.screenAudio)
        case .microphone:
            language.localized(.microphone)
        case .both:
            language.localized(.screenAndMic)
        }
    }
}

extension TranscriptViewMode {
    func localizedTitle(language: InterfaceLanguage) -> String {
        switch self {
        case .both:
            language.localized(.both)
        case .original:
            language.localized(.original)
        case .translated:
            language.localized(.translated)
        }
    }
}


extension SubtitleDisplayMode {
    func localizedTitle(language: InterfaceLanguage) -> String {
        switch self {
        case .translated:
            language.localized(.translated)
        case .original:
            language.localized(.original)
        case .bilingual:
            language.localized(.both)
        }
    }
}

extension GlobalShortcutAction {
    func localizedTitle(language: InterfaceLanguage) -> String {
        switch self {
        case .toggleTranslation:
            language.localized(.shortcutToggleTranslation)
        case .showCaptionWindow:
            language.localized(.shortcutShowCaptionWindow)
        case .toggleMute:
            language.localized(.shortcutToggleMute)
        }
    }
}

extension TranscriptExportFormat {
    func localizedTitle(language: InterfaceLanguage) -> String {
        switch self {
        case .srt:
            language.localized(.exportAsSRT)
        case .webVTT:
            language.localized(.exportAsWebVTT)
        case .markdown:
            language.localized(.exportAsMarkdown)
        case .plainText:
            language.localized(.exportAsPlainText)
        }
    }
}
